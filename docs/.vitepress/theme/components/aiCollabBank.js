// 认知题总评：一个称号 + 一句话
export function cognitionSummary(correct, total) {
  const ratio = total ? correct / total : 0
  if (ratio >= 0.9) return { title: 'AI 明白人', text: '你对 AI 的理解相当扎实，常见的坑基本都绕开了。' }
  if (ratio >= 0.65) return { title: '大体清醒', text: '大部分认知是对的，还有几块盲区，补上会少踩不少坑。' }
  if (ratio >= 0.4) return { title: '半信半疑', text: '基础有了，但有几处常见误区。这些误区不改，用得越多越容易踩坑。' }
  return { title: '容易被 AI 忽悠', text: '你对 AI 的不少印象还停在常见误区里。好消息是，这些误区补起来很快。' }
}

